"""Generate the Postgres Row-Level-Security migration from ``sql/tables.py``.

Usage::

    .venv/bin/python scripts/gen_rls_migration.py

Rewrites ``src/scinr/newton/sql/migrations/postgres/rls/0001_rls.sql``. Every table with a
``tenant_id`` column gets the four tenant policies, so the list of tables is never written by
hand: ``tests/unit/test_rls_migration.py`` regenerates in memory and fails when the committed
file is stale (a table was added without regenerating).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

TARGET = ROOT / "src/scinr/newton/sql/migrations/postgres/rls/0001_rls.sql"
SEPARATOR = "-- statement"

#: Stored ``tenant_id`` of public data (``utils.tenancy.PUBLIC_TENANT``).
PUBLIC_STORED = "__public__"
#: ``newton_tenant_access.tenant_id`` that grants public data.
PUBLIC_GRANT = "*"

HEADER = """\
-- Row-Level-Security track of the Postgres schema. GENERATED by scripts/gen_rls_migration.py
-- from sql/tables.py: do not edit by hand, regenerate.
-- Catalog tables (catalog_models, model_fields, entity_labels, themes, catalog_edges) and
-- newton_schema have no tenant_id and carry no policy: the catalog is shared (invariant I1).
-- Grants to the runtime role are not here: setup_sql_schema applies them per role."""

ACCESS_TABLE = f"""\
CREATE TABLE IF NOT EXISTS {{schema}}.newton_tenant_access (
    role_name  TEXT NOT NULL,
    tenant_id  TEXT NOT NULL,
    can_write  BOOLEAN NOT NULL DEFAULT false,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (role_name, tenant_id)
)
{SEPARATOR}
ALTER TABLE {{schema}}.newton_tenant_access ENABLE ROW LEVEL SECURITY
{SEPARATOR}
CREATE POLICY own_rows ON {{schema}}.newton_tenant_access FOR SELECT USING (role_name = current_user)"""

_TENANT_OF = f"CASE WHEN t IS NULL OR t = '{PUBLIC_STORED}' THEN '{PUBLIC_GRANT}' ELSE t END"

FUNCTIONS = f"""\
CREATE OR REPLACE FUNCTION {{schema}}.newton_can_read(t TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM {{schema}}.newton_tenant_access a
                   WHERE a.role_name = current_user AND a.tenant_id = {_TENANT_OF})
$$
{SEPARATOR}
CREATE OR REPLACE FUNCTION {{schema}}.newton_can_write(t TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM {{schema}}.newton_tenant_access a
                   WHERE a.role_name = current_user AND a.can_write
                     AND a.tenant_id = {_TENANT_OF})
$$"""

INDEX_FUNCTION = f"""\
CREATE OR REPLACE FUNCTION {{schema}}.newton_ensure_instance_key_index(prop TEXT)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF prop !~ '^[A-Za-z_][A-Za-z0-9_]{{0,62}}$' THEN
        RAISE EXCEPTION 'invalid property name %', prop USING ERRCODE = '22023';
    END IF;
    EXECUTE format(
        'CREATE INDEX IF NOT EXISTS %I ON {{schema}}.model_instances (tenant_id, (props ->> %L))',
        'model_instances_key_' || prop, prop);
END
$$
{SEPARATOR}
REVOKE ALL ON FUNCTION {{schema}}.newton_ensure_instance_key_index(TEXT) FROM PUBLIC"""


def tenant_tables() -> list[str]:
    """Names of the Postgres tables that have a ``tenant_id`` column, sorted."""
    from scinr.newton.sql.tables import metadata, storage_tables

    found = {
        table.name
        for table in (*metadata.tables.values(), *storage_tables("postgres"))
        if table is not None and "tenant_id" in table.c and not table.info.get("is_view")
    }
    return sorted(found)


def _policies(table: str) -> str:
    target = f"{{schema}}.{table}"
    return f"""\
ALTER TABLE {target} ENABLE ROW LEVEL SECURITY
{SEPARATOR}
ALTER TABLE {target} FORCE ROW LEVEL SECURITY
{SEPARATOR}
CREATE POLICY tenant_read ON {target} FOR SELECT USING ({{schema}}.newton_can_read(tenant_id))
{SEPARATOR}
CREATE POLICY tenant_ins ON {target} FOR INSERT WITH CHECK ({{schema}}.newton_can_write(tenant_id))
{SEPARATOR}
CREATE POLICY tenant_upd ON {target} FOR UPDATE USING ({{schema}}.newton_can_write(tenant_id))
    WITH CHECK ({{schema}}.newton_can_write(tenant_id))
{SEPARATOR}
CREATE POLICY tenant_del ON {target} FOR DELETE USING ({{schema}}.newton_can_write(tenant_id))"""


def render() -> str:
    """The text of ``0001_rls.sql`` for the current ``sql/tables.py``."""
    parts = [
        ACCESS_TABLE,
        FUNCTIONS,
        *(_policies(name) for name in tenant_tables()),
        INDEX_FUNCTION,
    ]
    return HEADER + "\n" + f"\n{SEPARATOR}\n".join(parts) + "\n"


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
